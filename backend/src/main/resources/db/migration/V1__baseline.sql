-- -----------------------------------------------------------------------------
-- audit_logs：Append Only，永不 UPDATE / DELETE
-- actor 信息保留快照（actor_username），不依赖外键，保证历史可追溯
-- -----------------------------------------------------------------------------
create table audit_logs (
  id             bigint generated by default as identity primary key,
  actor_user_id  bigint,
  actor_username varchar(64) not null,
  action         varchar(80) not null,
  resource_type  varchar(60),
  resource_id    varchar(64),
  before_data    jsonb,
  after_data     jsonb,
  reason         varchar(500),
  ip_address     varchar(45),
  user_agent     varchar(400),
  request_id     varchar(64),
  risk_level     varchar(20) not null default 'NORMAL',
  created_at     timestamptz not null default now()
);

create index ix_audit_logs_actor_time on audit_logs (actor_user_id, created_at desc);
create index ix_audit_logs_resource on audit_logs (resource_type, resource_id);
create index ix_audit_logs_action_time on audit_logs (action, created_at desc);
create index ix_audit_logs_created_at on audit_logs (created_at desc);

-- -----------------------------------------------------------------------------
-- security_events：高危安全事件，永久追加；预留哈希链字段
-- -----------------------------------------------------------------------------
create table security_events (
  id             bigint generated by default as identity primary key,
  event_type     varchar(80)  not null,
  severity       varchar(20)  not null default 'INFO',
  description    varchar(500) not null,
  detail         jsonb,
  actor_user_id  bigint,
  actor_username varchar(64),
  ip_address     varchar(45),
  user_agent     varchar(400),
  request_id     varchar(64),
  previous_hash  varchar(128),
  entry_hash     varchar(128),
  created_at     timestamptz  not null default now()
);

create index ix_security_events_type_time on security_events (event_type, created_at desc);
create index ix_security_events_created_at on security_events (created_at desc);